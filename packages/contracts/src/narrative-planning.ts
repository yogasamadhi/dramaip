import { z } from "zod";
import {
  NarrativeSourceBasisSchema,
  narrativeSourceIdentity,
  refineNarrativeSourceSelection,
} from "./narrative-context.js";
import { AgentContextEntrySchema } from "./agent-context.js";
import {
  NarrativeScopeChapterSchema,
  NarrativeSourceScopeFields,
  refineNarrativeSourceScope,
} from "./narrative-source-scope.js";

export const NarrativePlanningOperationSchema = z.enum([
  "characters",
  "book-outline",
  "chapter-outline",
  "story-arc",
  "knowledge-plan",
]);

const chapter = NarrativeScopeChapterSchema;

// Planning has no fabricated Chapter target. A blank story can explicitly use
// no manuscript; a selected/full manuscript scope is a separate author choice.
export const NarrativePlanningRequestSchema = z
  .object({
    format: z.literal("narrative-planning-v1"),
    ...NarrativeSourceScopeFields,
  })
  .strict()
  .superRefine(refineNarrativeSourceScope);

export type NarrativePlanningOperation = z.infer<
  typeof NarrativePlanningOperationSchema
>;
export type NarrativePlanningRequest = z.infer<
  typeof NarrativePlanningRequestSchema
>;

/** Shared metadata encoding only. Owners still verify the actual directory. */
export function narrativePlanningDirectory(
  chapters: readonly {
    id: string;
    version: number;
    orderIndex: number;
    content: string;
  }[],
) {
  return [...chapters]
    .sort((a, b) => a.orderIndex - b.orderIndex || a.id.localeCompare(b.id))
    .map(({ id, version, orderIndex, content }) => ({
      id,
      version,
      orderIndex,
      hasContent: Boolean(content.trim()),
    }));
}

export const NarrativePlanningSourceSchema = z
  .object({
    kind: z.literal("author-selected-narrative-planning"),
    projectId: z.string().uuid(),
    request: NarrativePlanningRequestSchema,
    sourceBasis: NarrativeSourceBasisSchema,
    coverage: z.object({
      included: z.array(
        chapter.extend({
          title: z.string(),
          representations: z
            .array(
              z.enum([
                "original",
                "summary",
                "paragraphs",
                "hierarchical-summary",
              ]),
            )
            .min(1),
        }),
      ),
      excluded: z.array(
        chapter.extend({ reason: z.enum(["not-selected", "empty"]) }),
      ),
      totalChapterCount: z.number().int().nonnegative(),
      nonEmptyChapterCount: z.number().int().nonnegative(),
    }),
  })
  .superRefine(refineNarrativeSourceSelection);

// This is generated by owners, not accepted from the author as source evidence.
export const NarrativePlanningBasisSchema =
  NarrativePlanningSourceSchema.safeExtend({
    operation: NarrativePlanningOperationSchema,
    references: z
      .array(
        z.object({
          sourceKind: AgentContextEntrySchema.shape.sourceKind,
          sourceId: z.string().min(1),
          sourceVersion: z.number().int().nonnegative(),
          fieldPath: z.string().startsWith("/"),
          contentHash: z.string().regex(/^[a-f0-9]{64}$/u),
          policyDependencies: AgentContextEntrySchema.shape.policyDependencies,
        }),
      )
      .min(1),
    contextBudget: z
      .object({
        source: z.literal("estimate"),
        tokenBudget: z.number().int().positive(),
        estimatedTokens: z.number().int().nonnegative(),
      })
      .optional(),
  });
export type NarrativePlanningSource = z.infer<
  typeof NarrativePlanningSourceSchema
>;
export type NarrativePlanningBasis = z.infer<
  typeof NarrativePlanningBasisSchema
>;

/** Unselected directory growth changes coverage metadata, not frozen inputs.
 * Full-scope validity is separately checked against its immutable fingerprint. */
export function narrativePlanningIdentity(
  basis: NarrativePlanningBasis,
): string {
  const value = NarrativePlanningBasisSchema.parse(basis);
  return JSON.stringify({
    kind: value.kind,
    projectId: value.projectId,
    operation: value.operation,
    request: value.request,
    sourceBasis: narrativeSourceIdentity(value.sourceBasis),
    references: value.references,
  });
}
